const {chromium}=require('C:/Users/LENOVO/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('fs'); const path=require('path');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const output=path.join(__dirname,'review');fs.mkdirSync(output,{recursive:true});
 const errors=[];
 const desktop=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
 desktop.on('pageerror',error=>errors.push(error.message));
 await desktop.goto('http://127.0.0.1:8766/gallery.html',{waitUntil:'networkidle'});
 await desktop.waitForTimeout(950);
 await desktop.screenshot({path:path.join(output,'gallery-desktop.png'),fullPage:true});
 const initial=await desktop.evaluate(()=>({title:document.title,options:document.querySelectorAll('#template-select option').length,status:document.getElementById('status-title').textContent,overflow:document.documentElement.scrollWidth>innerWidth,gsap:window.gsap?.version,loadedManifest:!!window.GALLERY_STATE?.manifest}));
 await desktop.selectOption('#template-select',{index:Math.min(initial.options-1,1)});
 await desktop.waitForTimeout(500);
 await desktop.uncheck('#guides');
 await desktop.waitForTimeout(400);
 const toggle=await desktop.evaluate(()=>({guides:document.getElementById('guides').checked,note:document.getElementById('stage-note').textContent,canvasVisible:!document.getElementById('fit-canvas').hidden,imageVisible:!document.getElementById('checked-preview').hidden}));
 await desktop.check('#guides');
 await desktop.click('#replay');
 await desktop.waitForTimeout(900);
 await desktop.locator('summary').click();
 await desktop.fill('#manifest-json','{broken');
 await desktop.click('#apply-manifest');
 const invalid=await desktop.textContent('#manifest-message');
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 mobile.on('pageerror',error=>errors.push(error.message));
 await mobile.goto('http://127.0.0.1:8766/gallery.html',{waitUntil:'networkidle'});
 await mobile.waitForTimeout(850);
 await mobile.screenshot({path:path.join(output,'gallery-mobile.png'),fullPage:true});
 const mobileChecks=await mobile.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,artLoaded:document.getElementById('artwork').naturalWidth>0,templateOptions:document.querySelectorAll('#template-select option').length,canvasSize:[document.getElementById('fit-canvas').width,document.getElementById('fit-canvas').height]}));
 const calm=await browser.newPage({viewport:{width:1280,height:900},reducedMotion:'reduce'});
 await calm.goto('http://127.0.0.1:8766/gallery.html',{waitUntil:'networkidle'});
 await calm.click('#replay');
 const reduced=await calm.evaluate(()=>({motionPreference:matchMedia('(prefers-reduced-motion: reduce)').matches,artTransform:getComputedStyle(document.getElementById('artwork')).transform}));
 const report={initial,toggle,invalid,mobileChecks,reduced,errors};fs.writeFileSync(path.join(output,'gallery-browser-check.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
